//! Generate the plugin contract from its Rust serde definitions. No JS codegen toolchain.
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result, bail, ensure};
use syn::{Attribute, Fields, GenericArgument, Item, LitStr, PathArguments, Type};

const BUN: &str = "crates/hya-plugin-bun/adapter/src";
const CLAUDE: &str = "crates/hya-plugin-claude/adapter/src";
const HEADER: &str = "// Generated by `cargo run -p xtask -- gen-plugin`; do not edit.\n";

pub fn run(args: Vec<String>) -> Result<()> {
    ensure!(args.is_empty(), "usage: cargo xtask gen-plugin");
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    for (path, bytes) in outputs(&root)? {
        std::fs::write(root.join(path), bytes)?;
    }
    Ok(())
}

struct Hook {
    ident: syn::Ident,
    wire: String,
    params: String,
    reply: String,
}

struct Hooks(Vec<Hook>);

impl syn::parse::Parse for Hooks {
    fn parse(input: syn::parse::ParseStream<'_>) -> syn::Result<Self> {
        fn name(ty: Type) -> syn::Result<String> {
            match ty {
                Type::Path(path) if path.path.segments.len() == 1 => {
                    Ok(path.path.segments[0].ident.to_string())
                }
                Type::Tuple(tuple) if tuple.elems.is_empty() => Ok("()".into()),
                other => Err(syn::Error::new_spanned(
                    other,
                    "hook payload must name a wire type or ()",
                )),
            }
        }
        let mut hooks = Vec::new();
        while !input.is_empty() {
            let _docs = input.call(Attribute::parse_outer)?;
            let ident = input.parse()?;
            input.parse::<syn::Token![:]>()?;
            let wire = input.parse::<LitStr>()?.value();
            input.parse::<syn::Token![=>]>()?;
            let params = name(input.parse()?)?;
            input.parse::<syn::Token![=>]>()?;
            let reply = name(input.parse()?)?;
            input.parse::<syn::Token![,]>()?;
            hooks.push(Hook {
                ident,
                wire,
                params,
                reply,
            });
        }
        Ok(Self(hooks))
    }
}

#[derive(Default)]
struct Serde {
    rename: Option<String>,
    rename_all: Option<String>,
    tag: Option<String>,
    content: Option<String>,
    default: bool,
    skip: bool,
    omit: bool,
    flatten: bool,
}

fn serde_attrs(attrs: &[Attribute]) -> Result<Serde> {
    let mut out = Serde::default();
    for attr in attrs.iter().filter(|a| a.path().is_ident("serde")) {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename") {
                out.rename = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("rename_all") {
                out.rename_all = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("tag") {
                out.tag = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("content") {
                out.content = Some(meta.value()?.parse::<LitStr>()?.value());
            } else if meta.path.is_ident("default") {
                out.default = true;
                if meta.input.peek(syn::Token![=]) {
                    let _ = meta.value()?.parse::<LitStr>()?;
                }
            } else if meta.path.is_ident("skip_serializing_if") {
                out.omit = true;
                let _ = meta.value()?.parse::<LitStr>()?;
            } else if meta.path.is_ident("skip") {
                out.skip = true;
            } else if meta.path.is_ident("flatten") {
                out.flatten = true;
            } else if meta.path.is_ident("alias") {
                let _ = meta.value()?.parse::<LitStr>()?;
            } else if !(meta.path.is_ident("transparent")
                || meta.path.is_ident("deny_unknown_fields")
                || meta.path.is_ident("other"))
            {
                return Err(meta.error("unsupported serde attribute in plugin wire contract"));
            }
            Ok(())
        })?;
    }
    Ok(out)
}

fn renamed(name: &str, rule: Option<&str>) -> Result<String> {
    Ok(match rule {
        None => name.to_owned(),
        Some("lowercase") => name.to_lowercase(),
        Some("snake_case") => name
            .chars()
            .enumerate()
            .fold(String::new(), |mut s, (i, c)| {
                if c.is_uppercase() && i > 0 {
                    s.push('_');
                }
                s.extend(c.to_lowercase());
                s
            }),
        Some("camelCase") => {
            let mut upper = false;
            name.chars()
                .filter_map(|c| {
                    if c == '_' {
                        upper = true;
                        None
                    } else if upper {
                        upper = false;
                        Some(c.to_ascii_uppercase())
                    } else {
                        Some(c)
                    }
                })
                .collect()
        }
        Some(rule) => bail!("unsupported serde rename rule: {rule}"),
    })
}

struct Generator {
    items: BTreeMap<String, Item>,
    pending: BTreeSet<String>,
    definitions: BTreeMap<String, String>,
}

impl Generator {
    fn load(root: &Path) -> Result<Self> {
        let mut generator = Self {
            items: BTreeMap::new(),
            pending: BTreeSet::new(),
            definitions: BTreeMap::new(),
        };
        let mut paths = vec![
            root.join("crates/hya-plugin/src/messages.rs"),
            root.join("crates/hya-tool/src/permission.rs"),
        ];
        // Resolve the domain types nested in Envelope, Message and ToolSchema too.
        for entry in std::fs::read_dir(root.join("crates/hya-proto/src"))? {
            let path = entry?.path();
            if path.extension().is_some_and(|ext| ext == "rs") {
                paths.push(path);
            }
        }
        paths.sort();
        for path in paths {
            for item in syn::parse_file(&std::fs::read_to_string(&path)?)?.items {
                let name = match &item {
                    Item::Struct(v) => v.ident.to_string(),
                    Item::Enum(v) => v.ident.to_string(),
                    Item::Type(v) => v.ident.to_string(),
                    Item::Macro(v)
                        if v.mac.path.is_ident("uuid_id") || v.mac.path.is_ident("str_newtype") =>
                    {
                        let name = v
                            .mac
                            .tokens
                            .clone()
                            .into_iter()
                            .next()
                            .context("newtype name")?
                            .to_string();
                        generator
                            .definitions
                            .insert(name.clone(), format!("export type {name} = string\n"));
                        continue;
                    }
                    _ => continue,
                };
                ensure!(
                    generator.items.insert(name.clone(), item).is_none(),
                    "duplicate wire type {name}"
                );
            }
        }
        // These types implement serde manually instead of deriving it.
        for name in ["SessionId", "WorkflowRevision"] {
            generator
                .definitions
                .insert(name.to_owned(), format!("export type {name} = string\n"));
        }
        Ok(generator)
    }

    fn ty(&mut self, ty: &Type) -> Result<String> {
        match ty {
            Type::Reference(v) => self.ty(&v.elem),
            Type::Slice(v) => Ok(format!("ReadonlyArray<{}>", self.ty(&v.elem)?)),
            Type::Array(v) => Ok(format!("ReadonlyArray<{}>", self.ty(&v.elem)?)),
            Type::Tuple(v) if v.elems.is_empty() => {
                Ok("Readonly<Record<string, never>>".to_owned())
            }
            Type::Path(v) => {
                let part = v.path.segments.last().context("wire type name")?;
                let name = part.ident.to_string();
                let args = match &part.arguments {
                    PathArguments::AngleBracketed(a) => a
                        .args
                        .iter()
                        .filter_map(|v| match v {
                            GenericArgument::Type(t) => Some(t),
                            _ => None,
                        })
                        .collect::<Vec<_>>(),
                    _ => Vec::new(),
                };
                match name.as_str() {
                    "str" | "String" | "Uuid" | "PathBuf" => Ok("string".into()),
                    "bool" => Ok("boolean".into()),
                    "u8" | "u16" | "u32" | "u64" | "usize" | "i32" | "i64" | "f32" | "f64"
                    | "Number" => Ok("number".into()),
                    "Value" => Ok("unknown".into()),
                    "Vec" | "BTreeSet" => Ok(format!("ReadonlyArray<{}>", self.ty(args[0])?)),
                    "BTreeMap" | "HashMap" => Ok(format!(
                        "Readonly<Record<{}, {}>>",
                        self.ty(args[0])?,
                        self.ty(args[1])?
                    )),
                    "Option" => Ok(format!("{} | null", self.ty(args[0])?)),
                    _ => {
                        self.pending.insert(name.clone());
                        Ok(name)
                    }
                }
            }
            _ => bail!("unsupported Rust type in plugin contract"),
        }
    }

    fn fields(&mut self, fields: &Fields, rule: Option<&str>) -> Result<String> {
        match fields {
            Fields::Unit => Ok("Readonly<Record<string, never>>".into()),
            Fields::Unnamed(v) if v.unnamed.len() == 1 => self.ty(&v.unnamed[0].ty),
            Fields::Named(v) => {
                let mut body = String::from("{\n");
                let mut flattened = Vec::new();
                for field in &v.named {
                    let attrs = serde_attrs(&field.attrs)?;
                    if attrs.skip {
                        continue;
                    }
                    let ty = self.ty(&field.ty)?;
                    if attrs.flatten {
                        flattened.push(ty);
                        continue;
                    }
                    let ident = field
                        .ident
                        .as_ref()
                        .context("named wire field")?
                        .to_string();
                    let name = attrs.rename.unwrap_or(renamed(&ident, rule)?);
                    // Serde accepts explicit null for Option, including omitted-on-output fields.
                    let optional = if attrs.default || attrs.omit { "?" } else { "" };
                    writeln!(body, "  readonly {name}{optional}: {ty}")?;
                }
                body.push('}');
                for flat in flattened {
                    write!(body, " & {flat}")?;
                }
                Ok(body)
            }
            _ => bail!("unsupported tuple in plugin contract"),
        }
    }

    fn guard(&self, ty: &Type, value: &str) -> Result<String> {
        match ty {
            Type::Reference(v) => self.guard(&v.elem, value),
            Type::Slice(v) => Ok(format!(
                "(Array.isArray({value}) && {value}.every((item: unknown) => {}))",
                self.guard(&v.elem, "item")?
            )),
            Type::Array(v) => Ok(format!(
                "(Array.isArray({value}) && {value}.every((item: unknown) => {}))",
                self.guard(&v.elem, "item")?
            )),
            Type::Path(v) => {
                let part = v.path.segments.last().context("guard type")?;
                let name = part.ident.to_string();
                let args = match &part.arguments {
                    PathArguments::AngleBracketed(a) => a
                        .args
                        .iter()
                        .filter_map(|v| match v {
                            GenericArgument::Type(t) => Some(t),
                            _ => None,
                        })
                        .collect::<Vec<_>>(),
                    _ => Vec::new(),
                };
                Ok(match name.as_str() {
                    "String" | "str" | "Uuid" | "PathBuf" => {
                        format!("typeof {value} === \"string\"")
                    }
                    "bool" => format!("typeof {value} === \"boolean\""),
                    "u8" | "u16" | "u32" | "u64" | "usize" => format!(
                        "(typeof {value} === \"number\" && Number.isInteger({value}) && {value} >= 0)"
                    ),
                    "i32" | "i64" => {
                        format!("(typeof {value} === \"number\" && Number.isInteger({value}))")
                    }
                    "f32" | "f64" | "Number" => {
                        format!("(typeof {value} === \"number\" && Number.isFinite({value}))")
                    }
                    "Value" => "true".into(),
                    "Vec" | "BTreeSet" => format!(
                        "(Array.isArray({value}) && {value}.every((item: unknown) => {}))",
                        self.guard(args[0], "item")?
                    ),
                    "Option" => format!("({value} === null || {})", self.guard(args[0], value)?),
                    "BTreeMap" | "HashMap" => format!(
                        "(isRecord({value}) && Object.entries({value}).every(([key, item]) => {} && {}))",
                        self.guard(args[0], "key")?,
                        self.guard(args[1], "item")?
                    ),
                    _ => format!("is{name}({value})"),
                })
            }
            _ => bail!("unsupported guard type"),
        }
    }

    fn field_guards(&self, fields: &Fields, rule: Option<&str>, value: &str) -> Result<String> {
        match fields {
            Fields::Unit => Ok("true".into()),
            Fields::Unnamed(v) if v.unnamed.len() == 1 => self.guard(&v.unnamed[0].ty, value),
            Fields::Named(v) => {
                let mut checks = vec![format!("isRecord({value})")];
                for field in &v.named {
                    let attrs = serde_attrs(&field.attrs)?;
                    if attrs.skip {
                        continue;
                    }
                    if attrs.flatten {
                        checks.push(self.guard(&field.ty, value)?);
                        continue;
                    }
                    let ident = field
                        .ident
                        .as_ref()
                        .context("named guard field")?
                        .to_string();
                    let name = attrs.rename.unwrap_or(renamed(&ident, rule)?);
                    let access = format!("{value}[{name:?}]");
                    let check = self.guard(&field.ty, &access)?;
                    checks.push(if attrs.omit || attrs.default {
                        format!("({access} === undefined || {check})")
                    } else {
                        format!("({name:?} in {value} && {check})")
                    });
                }
                Ok(checks.join(" && "))
            }
            _ => bail!("unsupported guard tuple"),
        }
    }

    fn item_guard(&self, item: &Item) -> Result<String> {
        match item {
            Item::Struct(v) => self.field_guards(
                &v.fields,
                serde_attrs(&v.attrs)?.rename_all.as_deref(),
                "value",
            ),
            Item::Type(v) => self.guard(&v.ty, "value"),
            Item::Enum(v) => {
                let attrs = serde_attrs(&v.attrs)?;
                let mut checks = Vec::new();
                for variant in &v.variants {
                    let va = serde_attrs(&variant.attrs)?;
                    let name = va.rename.unwrap_or(renamed(
                        &variant.ident.to_string(),
                        attrs.rename_all.as_deref(),
                    )?);
                    let unit = matches!(variant.fields, Fields::Unit);
                    let check = match (&attrs.tag, &attrs.content, unit) {
                        (Some(tag), _, true) => {
                            format!("isRecord(value) && value[{tag:?}] === {name:?}")
                        }
                        (Some(tag), Some(content), false) => format!(
                            "isRecord(value) && value[{tag:?}] === {name:?} && {}",
                            self.field_guards(
                                &variant.fields,
                                va.rename_all.as_deref(),
                                &format!("value[{content:?}]")
                            )?
                        ),
                        (Some(tag), None, false) => format!(
                            "isRecord(value) && value[{tag:?}] === {name:?} && {}",
                            self.field_guards(&variant.fields, va.rename_all.as_deref(), "value")?
                        ),
                        (None, _, true) => format!("value === {name:?}"),
                        (None, _, false) => format!(
                            "isRecord(value) && {}",
                            self.field_guards(
                                &variant.fields,
                                va.rename_all.as_deref(),
                                &format!("value[{name:?}]")
                            )?
                        ),
                    };
                    checks.push(format!("({check})"));
                }
                Ok(checks.join(" ||\n    "))
            }
            _ => bail!("not a guard type"),
        }
    }

    fn definition(&mut self, item: &Item) -> Result<String> {
        match item {
            Item::Struct(v) => self.fields(&v.fields, serde_attrs(&v.attrs)?.rename_all.as_deref()),
            Item::Type(v) => self.ty(&v.ty),
            Item::Enum(v) => {
                let attrs = serde_attrs(&v.attrs)?;
                let mut variants = Vec::new();
                for variant in &v.variants {
                    let va = serde_attrs(&variant.attrs)?;
                    let name = va.rename.unwrap_or(renamed(
                        &variant.ident.to_string(),
                        attrs.rename_all.as_deref(),
                    )?);
                    let literal = serde_json::to_string(&name)?;
                    let body = self.fields(&variant.fields, va.rename_all.as_deref())?;
                    let unit = matches!(variant.fields, Fields::Unit);
                    let shape = match (&attrs.tag, &attrs.content, unit) {
                        (Some(tag), _, true) => format!("{{ readonly {tag}: {literal} }}"),
                        (Some(tag), Some(content), false) => {
                            format!("{{ readonly {tag}: {literal}; readonly {content}: {body} }}")
                        }
                        (Some(tag), None, false) => {
                            format!("{{ readonly {tag}: {literal} }} & {body}")
                        }
                        (None, _, true) => literal,
                        (None, _, false) => format!("{{ readonly {literal}: {body} }}"),
                    };
                    variants.push(format!("({shape})"));
                }
                Ok(variants.join(" |\n"))
            }
            _ => bail!("not a wire type"),
        }
    }
}

fn outputs(root: &Path) -> Result<BTreeMap<PathBuf, String>> {
    let mut g = Generator::load(root)?;
    let source = syn::parse_file(&std::fs::read_to_string(
        root.join("crates/hya-plugin/src/messages.rs"),
    )?)?;
    let schema = source
        .items
        .into_iter()
        .find_map(|item| match item {
            Item::Macro(v) if v.mac.path.is_ident("plugin_hooks") => Some(v.mac.tokens),
            _ => None,
        })
        .context("plugin_hooks schema")?;
    let hooks = syn::parse2::<Hooks>(schema)?;
    let mut guards = BTreeMap::new();
    let mut hook_guards = String::from("export const HOOK_PARAM_GUARDS = {\n");
    let mut methods = String::from("export const HOOK_METHODS = {\n");
    let mut names = String::from("export const HOOK_NAMES = [\n");
    let mut params = String::from("export type HookParams = {\n");
    let mut replies = String::from("export type HookReplies = {\n");
    for hook in &hooks.0 {
        let wire = &hook.wire;
        let p = &hook.params;
        let r = &hook.reply;
        writeln!(names, "  {wire:?},")?;
        writeln!(
            methods,
            "  {}: {:?},",
            hook.ident,
            if wire == "event" {
                wire.clone()
            } else {
                format!("hook/{wire}")
            }
        )?;
        writeln!(hook_guards, "  {wire:?}: is{p},")?;
        g.pending.insert(p.clone());
        if r != "()" {
            g.pending.insert(r.clone());
        }
        writeln!(params, "  readonly {wire:?}: {p}")?;
        writeln!(
            replies,
            "  readonly {wire:?}: {}",
            if r == "()" {
                "Readonly<Record<string, never>>"
            } else {
                r
            }
        )?;
    }
    names.push_str("] as const\nexport type HookName = (typeof HOOK_NAMES)[number]\n");
    params.push_str("}\n");
    replies.push_str("}\n");
    methods.push_str("} as const\n");
    g.pending.insert("HookRegistration".into());
    g.pending.insert("ToolCallParams".into());
    guards.insert("HookName".into(), "export function isHookName(value: unknown): value is HookName { return typeof value === \"string\" && HOOK_NAMES.includes(value as HookName) }\n".into());
    // HookName is emitted as its literal union and runtime list above.
    g.definitions.insert("HookName".into(), String::new());
    while let Some(name) = g.pending.pop_first() {
        if g.definitions.contains_key(&name) {
            continue;
        }
        let item = g
            .items
            .get(&name)
            .with_context(|| format!("missing Rust wire definition for {name}"))?
            .clone();
        let body = g
            .definition(&item)
            .with_context(|| format!("generating {name}"))?;
        let guard = g.item_guard(&item)?;
        guards.insert(name.clone(), format!("export function is{name}(value: unknown): value is {name} {{\n  return {guard}\n}}\n"));
        g.definitions
            .insert(name.clone(), format!("export type {name} = {body}\n"));
    }
    for (name, definition) in &g.definitions {
        if definition.ends_with("= string\n") {
            guards.insert(name.clone(), format!("export function is{name}(value: unknown): value is {name} {{ return typeof value === \"string\" }}\n"));
        }
    }
    hook_guards.push_str("} as const\nexport function isHookParams<K extends HookName>(name: K, value: unknown): value is HookParams[K] {\n  return HOOK_PARAM_GUARDS[name](value)\n}\n");
    let ts = format!(
        "{HEADER}{names}\n{methods}\n{params}\n{replies}\n{}\nfunction isRecord(value: unknown): value is Record<string, unknown> {{\n  return typeof value === \"object\" && value !== null && !Array.isArray(value)\n}}\n\n{}\n{hook_guards}",
        g.definitions
            .values()
            .cloned()
            .collect::<Vec<_>>()
            .join("\n"),
        guards.values().cloned().collect::<Vec<_>>().join("\n")
    );
    let mut files = BTreeMap::new();
    for adapter in [BUN, CLAUDE] {
        files.insert(Path::new(adapter).join("wire.gen.ts"), ts.clone());
    }
    for file in ["protocol.ts", "stdio.ts"] {
        files.insert(
            Path::new(CLAUDE).join(file),
            std::fs::read_to_string(root.join(BUN).join(file))?,
        );
    }
    Ok(files)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn generated_plugin_contract_and_runtime_are_current() -> Result<()> {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        for (path, expected) in outputs(&root)? {
            ensure!(
                std::fs::read_to_string(root.join(&path))? == expected,
                "stale {}; run cargo run -p xtask -- gen-plugin",
                path.display()
            );
        }
        Ok(())
    }
}
